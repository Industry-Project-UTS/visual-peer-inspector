"""Standard-library bootstrap for prepared current 09/10 source snapshots.

This helper never downloads packages or alters the notebook kernel environment.
An optional explicit offline wheel install uses a new private target directory.
"""
from __future__ import annotations

import hashlib
import importlib.metadata
import json
import os
from pathlib import Path, PurePosixPath
import platform
import shutil
import subprocess
import sys
import tempfile

MANIFEST = 'prepared_source_manifest.json'
SCHEMA = 'vpi-current-notebook-source/v1'
CONTRACT = 'requirements/current-evaluation-runtime.json'


def digest(path):
    value = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            value.update(block)
    return value.hexdigest()


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=True).encode()


def atomic_json(path, value):
    path = Path(path); path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + '.partial')
    temporary.write_text(json.dumps(value, sort_keys=True, indent=2) + '\n')
    os.replace(temporary, path)


def safe_relative(name):
    value = PurePosixPath(name)
    if not name or '\\' in name or '\x00' in name or value.is_absolute() or any(p in {'', '.', '..'} for p in name.split('/')):
        raise ValueError('Unsafe prepared-source path')
    return value


def verify_source(root, notebook_relative=None):
    root = Path(root).resolve(strict=True)
    record = json.loads((root / MANIFEST).read_text())
    if record.get('schema') != SCHEMA or record.get('source_state') != 'working_directory_snapshot':
        raise ValueError('Expected an explicit prepared working-directory source snapshot')
    files = record.get('files', {})
    if not files or record.get('snapshot_sha256') != hashlib.sha256(canonical(files)).hexdigest():
        raise ValueError('Prepared source inventory hash differs')
    required = {'scripts/current_notebook_runtime.py', CONTRACT}
    if notebook_relative:
        required.add(notebook_relative)
    if not required <= set(files):
        raise ValueError('Prepared source snapshot omits bootstrap, runtime contract or notebook')
    for name, expected in files.items():
        safe_relative(name); path = root / name
        if path.is_symlink() or not path.is_file() or root not in path.resolve().parents or digest(path) != expected:
            raise ValueError('Prepared source file is missing, changed or outside its snapshot')
    # Reject injected importable files, while allowing Python bytecode generated by imports.
    for directory in ('src', 'scripts'):
        actual = {p.relative_to(root).as_posix() for p in (root / directory).rglob('*')
                  if p.is_file() and '__pycache__' not in p.parts and p.suffix in {'.py', '.json'}}
        if not actual <= set(files):
            raise ValueError('Unregistered executable/config source in prepared snapshot')
    return record


def bounded_roots(mount=Path('/kaggle/input')):
    mount = Path(mount)
    if not mount.is_dir():
        return []
    def children(path):
        values = sorted(p for p in path.iterdir() if p.is_dir())
        if len(values) > 250:
            raise ValueError('Input discovery exceeded its bounded directory inventory; set an explicit root')
        return values
    roots = [p for p in children(mount) if p.name not in {'datasets', 'notebooks', 'models'}]
    for category, depth in (('datasets', 2), ('notebooks', 2), ('models', 4)):
        current = [mount / category] if (mount / category).is_dir() else []
        for _ in range(depth):
            current = [child for parent in current for child in children(parent)]
            if len(current) > 1000:
                raise ValueError('Input discovery exceeded its bounded mount inventory')
        for path in current:
            roots.extend(children(path / 'versions') if (path / 'versions').is_dir() else [path])
    return sorted(set(roots))


def _resolve_config(stage, source_root, *, environ=None, mount=Path('/kaggle/input')):
    environ = os.environ if environ is None else environ
    configured = environ.get('VPI_NEXT_CONFIG') or environ.get('VPI_CURRENT_STAGE_CONFIG')
    if configured:
        paths = [Path(configured).expanduser()]
    else:
        name = stage.lower() + '-current-config.json'
        paths = [Path(source_root) / '.local' / name]
        for root in bounded_roots(mount):
            paths.extend(root / suffix / name for suffix in ('', 'config', 'configs', 'configuration'))
    matches = sorted({p.resolve() for p in paths if p.is_file()})
    if not matches:
        raise FileNotFoundError('Set VPI_NEXT_CONFIG to the reviewed current-stage JSON configuration')
    if len(matches) != 1:
        raise ValueError('Ambiguous stage configurations; set VPI_NEXT_CONFIG explicitly')
    data = json.loads(matches[0].read_text())
    if not isinstance(data, dict):
        raise ValueError('Stage configuration must be a JSON object')
    return data


def installed_versions(packages):
    result = {}
    for name in packages:
        try:
            result[name] = importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            result[name] = None
    return result


def check_runtime(contract, *, versions=None, python_version=None):
    actual_python = platform.python_version() if python_version is None else python_version
    actual = installed_versions(contract['packages']) if versions is None else versions
    differences = {name: {'expected': expected, 'actual': actual.get(name)} for name, expected in contract['packages'].items() if actual.get(name) != expected}
    if actual_python != contract['python'] or differences:
        details = {'expected_python': contract['python'], 'actual_python': actual_python, 'package_differences': differences}
        raise RuntimeError('Pinned runtime mismatch before scientific imports: ' + json.dumps(details, sort_keys=True))
    return {'python': actual_python, 'packages': actual, 'device_contract': contract.get('device','cpu')+' dependency metadata verified; no model execution implied'}


def install_offline(contract, wheelhouse, target, *, timeout=300):
    """Only explicit verified wheels; bounded install into a previously unused target."""
    if not 1 <= timeout <= 1800:
        raise ValueError('Offline dependency timeout must be bounded to 1,800 seconds')
    wheelhouse, target = Path(wheelhouse), runtime_target(target)
    manifest = json.loads((wheelhouse / 'wheelhouse_manifest.json').read_text())
    if manifest.get('schema') != 'vpi-current-offline-wheels/v1' or manifest.get('runtime_contract') != contract:
        raise ValueError('Offline wheelhouse does not match the selected runtime contract')
    files = manifest.get('files', {})
    actual = {p.name for p in wheelhouse.iterdir() if p.is_file() and p.suffix == '.whl'}
    if not files or set(files) != actual:
        raise ValueError('Offline wheel inventory is incomplete or contains unregistered wheels')
    for name, expected in files.items():
        safe_relative(name)
        if len(PurePosixPath(name).parts) != 1 or (wheelhouse / name).is_symlink() or digest(wheelhouse / name) != expected:
            raise ValueError('Offline wheel integrity check failed')
    resolved=manifest.get('resolved_packages',contract['packages'])
    if not isinstance(resolved,dict) or any(resolved.get(name.lower().replace('_','-'),resolved.get(name))!=version for name,version in contract['packages'].items()):
        raise ValueError('Offline resolved dependencies changed exact required pins')
    if target.exists():
        raise ValueError('Dependency target already exists; preserve it and choose a fresh directory')
    if any(name in sys.modules for name in ('numpy', 'pandas', 'scipy', 'matplotlib', 'PIL')):
        raise RuntimeError('Restart the kernel before changing already imported scientific dependencies')
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = Path(tempfile.mkdtemp(prefix=target.name + '.partial-', dir=target.parent))
    command = [sys.executable, '-m', 'pip', 'install', '--disable-pip-version-check', '--no-input',
               '--no-index', '--no-deps', '--find-links', str(wheelhouse), '--target', str(temporary)]
    command += [f'{name}=={version}' for name, version in resolved.items()]
    try:
        subprocess.run(command, check=True, timeout=timeout, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        found = {d.metadata['Name'].lower().replace('_', '-'): d.version for d in importlib.metadata.distributions(path=[str(temporary)])}
        if any(found.get(name.lower().replace('_', '-')) != value for name, value in resolved.items()):
            raise ValueError('Offline installation did not produce the exact runtime')
        atomic_json(temporary / 'dependency_receipt.json', {'status': 'verified', 'runtime_contract': contract,
                    'wheelhouse_manifest_sha256': digest(wheelhouse / 'wheelhouse_manifest.json')})
        os.replace(temporary, target)
        _retain_dependency_receipt(target, {'status': 'verified', 'runtime_contract_sha256': hashlib.sha256(canonical(contract)).hexdigest(), 'wheelhouse_manifest_sha256': digest(wheelhouse / 'wheelhouse_manifest.json'), 'ephemeral_dependency_target': True})
    except BaseException as exc:
        atomic_json(temporary / 'failure_receipt.json', {'status': 'failed', 'error_type': type(exc).__name__})
        _retain_dependency_receipt(target, {'status': 'failed', 'error_type': type(exc).__name__, 'scientific_run_started': False})
        raise RuntimeError('Offline dependency setup failed; retained failure receipt, no scientific code imported') from None
    return target


def bootstrap(source_root, notebook_relative, *, environ=None, runtime_profile=None):
    environ = os.environ if environ is None else environ
    root = Path(source_root).resolve(strict=True)
    source = verify_source(root, notebook_relative)
    profile = None
    runtime_profile = runtime_profile or environ.get('VPI_BASE_RUNTIME_PROFILE')
    if runtime_profile:
        safe_relative(runtime_profile)
        if runtime_profile not in source['files']:
            raise ValueError('Runtime profile is not sealed in the prepared source package')
        profile = json.loads((root/runtime_profile).read_text())
        if profile.get('schema') != 'vpi-runtime-compatibility-profile/v1':
            raise ValueError('Unrecognized exact runtime profile')
        contract = profile['runtime_contract']
    else:
        contract = json.loads((root / CONTRACT).read_text())
    base_contract = contract
    if environ.get('VPI_RUNTIME_PROFILE_ROOT'):
        contract = observed_contract(environ['VPI_RUNTIME_PROFILE_ROOT'], root/(runtime_profile or CONTRACT), contract)
    if platform.python_version() != contract['python']:
        _preflight_receipt(contract, environ)
        check_runtime(contract)
    target = environ.get('VPI_PACKAGE_TARGET')
    if target:
        target = runtime_target(target)
    if target and Path(target).exists():
        receipt = json.loads((Path(target) / 'dependency_receipt.json').read_text())
        if receipt.get('runtime_contract') != base_contract:
            raise ValueError('Existing dependency target differs from the pinned contract')
        sys.path.insert(0, str(Path(target).resolve()))
    try:
        runtime = check_runtime(contract)
    except RuntimeError:
        if environ.get('VPI_INSTALL_DEPENDENCIES') != '1' or not target or not environ.get('VPI_WHEELHOUSE'):
            _preflight_receipt(contract, environ)
            raise
        install_offline(base_contract, environ['VPI_WHEELHOUSE'], target, timeout=900 if 'torch' in base_contract['packages'] else 300)
        sys.path.insert(0, str(Path(target).resolve()))
        runtime = check_runtime(contract)
    sys.path.insert(0, str(root / 'src'))
    sys.path.insert(0, str(root / 'scripts'))
    provenance = {'source_state': source['source_state'], 'snapshot_sha256': source['snapshot_sha256'],
                  'source_manifest_sha256': digest(root / MANIFEST), 'notebook_sha256': source['files'][notebook_relative],
                  'base_commit': source.get('base_commit'), 'git_clean_claim': False,
                  'runtime_profile':runtime_profile or CONTRACT, 'runtime_contract_sha256':hashlib.sha256(canonical(contract)).hexdigest()}
    return {'source_root': root, 'provenance': provenance, 'runtime': runtime}


def runtime_target(path, *, kaggle=None):
    """Keep installed package files out of retained Kaggle scientific output."""
    target = Path(path).expanduser().resolve()
    kaggle = Path('/kaggle').is_dir() if kaggle is None else kaggle
    if kaggle:
        temporary_root = Path('/tmp').resolve()
        if not target.is_relative_to(temporary_root):
            raise ValueError('Kaggle dependency targets must be fresh /tmp/vpi-runtime-* directories')
        parts = target.relative_to(temporary_root).parts
        if not parts or not parts[0].startswith('vpi-runtime-') or parts[0] == 'vpi-runtime-':
            raise ValueError('Kaggle dependency targets require the /tmp/vpi-runtime-* prefix')
    return target


def _retain_dependency_receipt(target, receipt):
    if Path('/kaggle').is_dir():
        atomic_json(Path('/kaggle/working/runtime-receipts') / (Path(target).name + '.json'), receipt)


def writable_output(path):
    target = Path(path).expanduser().resolve()
    if Path('/kaggle').is_dir() and not target.is_relative_to(Path('/kaggle/working')):
        raise ValueError('Kaggle scientific output, receipt and recovery paths must be inside /kaggle/working')
    return target


def _preflight_receipt(contract, environ):
    default = '/kaggle/working/runtime-receipts/bootstrap-runtime.json' if Path('/kaggle').is_dir() else str(Path.cwd()/'.local/runtime-receipts/bootstrap-runtime.json')
    target = writable_output(environ.get('VPI_BOOTSTRAP_RECEIPT', default))
    atomic_json(target, {'status':'runtime_mismatch','expected_python':contract['python'],
        'actual_python':platform.python_version(),'expected_packages':contract['packages'],
        'actual_packages':installed_versions(contract['packages']), 'scientific_imports_started':False,
        'target_linux_profile_verified':contract.get('kaggle_linux_wheels_verified',False)})


def resolve_config(stage, source_root, *, environ=None, mount=Path('/kaggle/input')):
    try:
        return _resolve_config(stage, source_root, environ=environ, mount=mount)
    except BaseException as error:
        receipt_root=Path('/kaggle/working/runtime-receipts') if Path('/kaggle').is_dir() else Path.cwd()/'.local/runtime-receipts'
        atomic_json(receipt_root/(str(stage)+'-configuration-failure.json'),
            {'stage':stage,'status':'configuration_failed','error_type':type(error).__name__,
             'scientific_run_started':False})
        raise


def verify_model_snapshot(root,expected_model_id,expected_revision):
    """Verify a separately prepared local immutable model resource, without loading it."""
    root=Path(root).resolve(strict=True);manifest=root/'model_snapshot.json'
    record=json.loads(manifest.read_text())
    if record.get('schema')!='vpi-immutable-model-snapshot/v1' or record.get('model_id')!=expected_model_id or record.get('revision')!=expected_revision:
        raise ValueError('Model snapshot ID or immutable revision differs')
    if len(expected_revision)!=40 or any(c not in '0123456789abcdef' for c in expected_revision):
        raise ValueError('Model revision must be an exact40-character commit')
    files=record.get('files',{})
    if not files or not any(name.endswith(('.safetensors','.bin','.pt')) for name in files):
        raise ValueError('Model snapshot omits immutable weights')
    actual={p.relative_to(root).as_posix() for p in root.rglob('*') if p.is_file() and p.name!='model_snapshot.json'}
    if actual!=set(files):raise ValueError('Model snapshot has extra or missing files')
    for name,expected in files.items():
        safe_relative(name);path=root/name
        if path.is_symlink() or not path.resolve().is_relative_to(root) or digest(path)!=expected:
            raise ValueError('Model snapshot source or weight checksum differs')
    return {'status':'model_snapshot_verified','model_id':expected_model_id,'revision':expected_revision,
            'manifest_sha256':digest(manifest),'file_count':len(files),'model_loaded':False}


def observed_contract(profile_root,base_profile,base_contract):
    root=Path(profile_root);lock=json.loads((root/'runtime_profile_lock.json').read_text())
    if lock.get('schema')!='vpi-observed-runtime-lock/v1' or set(lock.get('files',{}))!={'runtime_profile.json','setup_probe.json'}:
        raise ValueError('Observed runtime profile seal is incomplete')
    if any((root/name).is_symlink() or digest(root/name)!=expected for name,expected in lock['files'].items()):
        raise ValueError('Observed runtime profile was modified')
    profile=json.loads((root/'runtime_profile.json').read_text());probe=json.loads((root/'setup_probe.json').read_text())
    if profile.get('schema')!='vpi-observed-runtime-profile/v1' or profile.get('base_profile_sha256')!=digest(base_profile) or profile.get('setup_probe_sha256')!=digest(root/'setup_probe.json'):
        raise ValueError('Observed runtime does not extend the exact registered profile')
    contract=profile['runtime_contract']
    if {k:v for k,v in contract.items() if k!='python'}!={k:v for k,v in base_contract.items() if k!='python'}:
        raise ValueError('Runtime setup changed scientific package pins or device contract')
    if not contract['python'].startswith('3.12.') or probe.get('python')!=contract['python'] or probe.get('packages')!=contract['packages'] or probe.get('system')!='Linux' or probe.get('machine')!='x86_64':
        raise ValueError('Observed Linux CPython3.12 setup evidence is inconsistent')
    if probe.get('status')!='package_metadata_verified' or probe.get('model_or_dataset_access') is not False:
        raise ValueError('Expected setup-only runtime observation')
    return contract


def configure_tracking_runtime(source_root, *, allow_install=False, environ=None):
    """Verify a separate publisher target and propagate it into bounded children."""
    environ = os.environ if environ is None else environ
    keys = ('VPI_TRACKING_PROFILE_ROOT', 'VPI_TRACKING_WHEELHOUSE', 'VPI_TRACKING_TARGET')
    values = [environ.get(key) for key in keys]
    if not any(values):
        if Path('/kaggle').is_dir():
            raise ValueError('Configure the separate pinned tracking runtime before publication')
        return {'status': 'local_existing_runtime', 'pinned_tracking_runtime': False}
    if not all(values):
        raise ValueError('Tracking setup needs its observed profile, wheelhouse and private target')
    root = Path(source_root).resolve(strict=True)
    source = verify_source(root)
    relative = 'requirements/profiles/linux-tracking-cp312.json'
    if relative not in source['files']:
        raise ValueError('Prepared source omits the registered tracking profile')
    path = root / relative
    profile = json.loads(path.read_text())
    base = profile['runtime_contract']
    contract = observed_contract(values[0], path, base)
    target = runtime_target(values[2])
    if not target.exists():
        if not allow_install:
            raise ValueError('Prepare the separate tracking target before starting bounded publication')
        install_offline(base, values[1], target, timeout=300)
    receipt = json.loads((target / 'dependency_receipt.json').read_text())
    if (receipt.get('runtime_contract') != base
            or receipt.get('wheelhouse_manifest_sha256') != digest(Path(values[1]) / 'wheelhouse_manifest.json')):
        raise ValueError('Tracking dependency target does not match its verified setup package')
    sys.path.insert(0, str(target))
    runtime = check_runtime(contract)
    prefixes = [str(target), str(root / 'scripts'), str(root / 'src')]
    existing = environ.get('PYTHONPATH')
    environ['PYTHONPATH'] = os.pathsep.join(prefixes + ([existing] if existing else []))
    return {'status': 'pinned_tracking_runtime_ready', 'pinned_tracking_runtime': True,
        'profile_sha256': digest(path), 'runtime': runtime, 'service_contacted': False}


def run_model_asset_preparation(source_root, output_root, selection, dependency_target, *, per_model_timeout=1800):
    """Bound all selected downloads together, including child-process cleanup."""
    import signal
    counts = {'all': 3, 'regions': 2, 'locateanything': 1, 'sam2': 1, 'dino': 1}
    if selection not in counts or not isinstance(per_model_timeout, int) or not 1 <= per_model_timeout <= 1800:
        raise ValueError('Select registered model assets and a bounded per-model timeout')
    root = writable_output(output_root)
    root.mkdir(parents=True, exist_ok=True)
    # Each model has its own download timeout plus bounded allowance for checksum verification.
    outer_timeout = counts[selection] * (per_model_timeout + 120)
    command = [sys.executable, str(Path(source_root) / 'scripts/prepare_current_model_assets.py'),
        '--source-root', str(source_root), '--output-root', str(root), '--only', selection,
        '--timeout-seconds', str(per_model_timeout)]
    environment = {**os.environ, 'PYTHONPATH': os.pathsep.join([str(dependency_target), str(Path(source_root) / 'src')])}
    child = subprocess.Popen(command, env=environment, start_new_session=True)
    receipt = {'selection': selection, 'model_count': counts[selection],
        'outer_timeout_seconds': outer_timeout, 'per_model_download_timeout_seconds': per_model_timeout,
        'model_inference_executed': False}
    try:
        return_code = child.wait(timeout=outer_timeout)
        if return_code:
            raise subprocess.CalledProcessError(return_code, command)
    except BaseException as error:
        if child.poll() is None:
            try:
                os.killpg(child.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
            child.wait()
        atomic_json(root / 'download-wrapper-receipt.json', {**receipt, 'status': 'failed', 'error_type': type(error).__name__})
        raise
    atomic_json(root / 'download-wrapper-receipt.json', {**receipt, 'status': 'prepared'})
    return receipt
